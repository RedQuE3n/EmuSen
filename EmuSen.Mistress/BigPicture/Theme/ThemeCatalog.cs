        private static readonly Dictionary<string, ThemeElementSpec> ByType = Elements.ToDictionary(e => e.Type, StringComparer.Ordinal);

        public static ThemeElementSpec? Find(string type) => ByType.GetValueOrDefault(type);

        public static int PropertyCount => Elements.Sum(e => e.Properties.Count);

        private static ThemePropertySpec Pair(string name, string? def, float? min = null, float? max = null) =>
            new(name, ThemePropertyType.NormalizedPair) { Default = def, Min = min, Max = max };

        private static ThemePropertySpec Path(string name) => new(name, ThemePropertyType.Path);

        private static ThemePropertySpec Bool(string name, string? def) => new(name, ThemePropertyType.Boolean) { Default = def };

        private static ThemePropertySpec Color(string name, string? def) => new(name, ThemePropertyType.Color) { Default = def };

        private static ThemePropertySpec UInt(string name, string? def, float? min = null, float? max = null) =>
            new(name, ThemePropertyType.UnsignedInteger) { Default = def, Min = min, Max = max };

        private static ThemePropertySpec Float(string name, string? def, float? min = null, float? max = null) =>
            new(name, ThemePropertyType.Float) { Default = def, Min = min, Max = max };

        private static ThemePropertySpec Str(string name, string? def) => new(name, ThemePropertyType.String) { Default = def };

        private static ThemePropertySpec Enum(string name, string? def, string values) =>
            new(name, ThemePropertyType.String) { Default = def, Shape = ThemeValueShape.Enum, Values = ThemeLists.Split(values) };

        private static ThemePropertySpec List(string name, string? def, string values, int maxItems) =>
            new(name, ThemePropertyType.String) { Default = def, Shape = ThemeValueShape.List, Values = ThemeLists.Split(values), MaxItems = maxItems };

        private static ThemePropertySpec Keyed(string name, string attribute, string keys) =>
            new(name, ThemePropertyType.Path) { Shape = ThemeValueShape.Keyed, KeyAttribute = attribute, Values = ThemeLists.Split(keys) };
    }

        public const int PaletteCount = 94;

        // Old licensee $01, or $33 with the new licensee "01": the boot ROM colours only Nintendo's games.
        public static bool IsNintendo(ReadOnlySpan<byte> rom) =>
            rom[0x14B] == 0x33 ? rom[0x144] == (byte)'0' && rom[0x145] == (byte)'1' : rom[0x14B] == 0x01;

        // The 8-bit sum of the sixteen bytes $0134-$0143, the CGB flag included.
        public static byte TitleChecksum(ReadOnlySpan<byte> rom)
        {
            byte sum = 0;
            for (int address = 0x134; address <= 0x143; address++) sum += rom[address];
            return sum;
        }

        // What the boot ROM leaves in B: the checksum it computed, which it computes only for Nintendo's games.
        public static byte HandOffChecksum(ReadOnlySpan<byte> rom) => IsNintendo(rom) ? TitleChecksum(rom) : (byte)0;

        // The palette number: 0, the default, for a game not Nintendo's, not listed, or with no matching fourth letter.
        public static int PaletteNumber(ReadOnlySpan<byte> rom)
        {
            if (!IsNintendo(rom)) return 0;
            int index = Array.IndexOf(TitleChecksums, TitleChecksum(rom));
            if (index < 0) return 0;
            if (index < FirstAmbiguous) return index;

            int column = index - FirstAmbiguous;
            for (int row = 0; ; row++)
            {
                int number = FirstAmbiguous + column + row * (TitleChecksums.Length - FirstAmbiguous);
                if (number >= PaletteCount) return 0;
                if (FourthLetters[column + row * (TitleChecksums.Length - FirstAmbiguous)] == rom[0x137]) return number;
            }
        }

        // Background palette 0, then object palettes 0 and 1, four colours each.
        public static (ushort[] Background, ushort[] Object0, ushort[] Object1) ForNumber(int number)
        {
            byte flags = IndexesAndFlags[number];
            int row = (flags & 0x1F) * 3;
            byte e0 = Triplets[row], e1 = Triplets[row + 1], e2 = Triplets[row + 2];
            byte obj0 = (flags & 0x20) != 0 ? e0 : e2;
            byte obj1 = (flags & 0x80) != 0 ? e1 : (flags & 0x40) != 0 ? e0 : e2;
            return (Read(e2), Read(obj0), Read(obj1));
        }

        // Every offset is even, so four colours start at a word; an offset that is not a multiple of eight simply starts mid-palette.
        private static ushort[] Read(byte offset) => Colours.AsSpan(offset >> 1, 4).ToArray();

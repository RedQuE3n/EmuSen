    public enum ThemeViewScope { Any, System, Gamelist }

    public enum ThemeElementGroup { Primary, Secondary, Special }

    [Flags]
    public enum ThemeElementViews { System = 1, Gamelist = 2, All = 4, SystemAndGamelist = System | Gamelist }

    // How a STRING property's text is read: free text, one of a set, a list of a set, or a PATH keyed by an attribute.
    public enum ThemeValueShape { Single, Enum, List, Keyed }

    // Per-axis rules the reference section gives for particular pairs - see EmuSen_BigPicture.md §12.2.
    public enum PairRule { Clamp, ZeroAxisAuto, MinusOneMatchesOther, OneAxisOnly }

    // Defaults the reference states in words rather than as a literal - see EmuSen_BigPicture.md §12.2.
    public enum ComputedDefault
    {
        None,
        SystemFullName,
        ElementWidth,
        OneAndAHalfFontSize,
        HelpPosByOrientation,
        HelpFontSizeByOrientation,
        InterpolationByRotation,
        ContainerForDescription,
        DisplayRelativeForLastPlayed,
        ContainerStartDelayByType,
    }

    // One documented property: its type, default, range, values and the view it is limited to.
    public sealed record ThemePropertySpec(string Name, ThemePropertyType Type)
    {
        public string? Default { get; init; }
        public string? DefaultSameAs { get; init; }
        public ComputedDefault Computed { get; init; }
        public float? Min { get; init; }
        public float? Max { get; init; }
        public float? MaxY { get; init; }
        public PairRule Rule { get; init; }
        public ThemeValueShape Shape { get; init; }
        public IReadOnlyList<string> Values { get; init; } = [];
        public int MaxItems { get; init; }
        public string? KeyAttribute { get; init; }
        public ThemeViewScope OnlyIn { get; init; }
        public string? Deferred { get; init; }
    }

    // One documented element type and its properties.
    public sealed class ThemeElementSpec
    {
        private readonly Dictionary<string, ThemePropertySpec> _byName;

        public ThemeElementSpec(string type, ThemeElementGroup group, ThemeElementViews views, IReadOnlyList<ThemePropertySpec> properties)
        {
            Type = type;
            Group = group;
            Views = views;
            Properties = properties;
            _byName = properties.ToDictionary(p => p.Name, StringComparer.Ordinal);
        }

        public string Type { get; }
        public ThemeElementGroup Group { get; }
        public ThemeElementViews Views { get; }
        public IReadOnlyList<ThemePropertySpec> Properties { get; }

        // Only helpsystem, clock and systemstatus lack one; they draw above everything - see EmuSen_BigPicture.md §12.2.
        public float? DefaultZIndex => _byName.TryGetValue("zIndex", out ThemePropertySpec? z) ? float.Parse(z.Default!, System.Globalization.CultureInfo.InvariantCulture) : null;

        public ThemePropertySpec? Find(string name) => _byName.GetValueOrDefault(name);
    }


            byte[] rom = SyntheticGbRom.Build(romBanks: 8, cartridgeType: kind, ramSizeCode: ramCode, cgbFlag: cgb);
            noise.NextBytes(rom.AsSpan(0x150, 0x8000 - 0x150));
            noise.NextBytes(rom.AsSpan(0x8000));
            if (seed >= 4)
